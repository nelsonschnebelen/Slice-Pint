#!/usr/bin/env python3
"""Builds one private-events page per location from src/template.html.
Edit the template or LOCATIONS below, then run: python3 build.py"""
import json, os

COMMON = {
    "liveHosts": ["sliceandpint.netlify.app"],  # add the custom domain here when there is one
    "formAction": "/",                          # Netlify Forms endpoint
    "minSpendFaq": False,  # $200 min-spend preorder for parties over 16; pending approval
    "menuUrl": "",         # verified official menu URL
    "phone": "",           # public restaurant phone, reconfirm before adding
    "privacyUrl": "",      # verified applicable policy URL
    "captureUtm": False,   # only under an approved consent setup
    "debugTracking": False,
}

LOCATIONS = [
    {
        "out": "index.html", "root": "",
        "loc": "Redondo Beach", "form": "redondo-event-inquiry",
        "address": "601 North Pacific Coast Highway<br>Redondo Beach, CA 90277",
        "space": "Our Redondo Beach location has a private dining room for groups who want a spot of their own, with the same pizza and beer you already come in for.",
        "gallery": True,
        "food_alt": "A pepperoni pizza from The Slice &amp; Pint",
        "assets": {"hero": "redondo-private-dining.webp", "food": "pepperoni.webp",
                   "room1": "room-1.webp", "room2": "room-2.webp"},
        "alts": {"hero": "The private dining room: one long wooden table with black chairs, two TVs and a window",
                 "room1": "Dining room with long wooden communal tables, bar stools and glass roll-up doors",
                 "room2": "Dining room with wooden tables and benches under string lights and tall windows"},
        "dims": {"hero": [1600, 1067], "food": [720, 820], "room1": [418, 400], "room2": [348, 348]},
        "capacityText": "",  # client email: ~30 seated / 40 standing; website says 20/35. Pending sign-off.
    },
    {
        "out": "el-segundo/index.html", "root": "../",
        "loc": "El Segundo", "form": "el-segundo-event-inquiry",
        "address": "130 West Grand Avenue<br>El Segundo, CA 90245",
        "space": "Our El Segundo location on Grand Avenue has the Dugout, a separate dining area with long picnic tables and plenty of TVs, with the same pizza and beer you already come in for.",
        "gallery": False,
        "food_alt": "A pizza with basil from The Slice &amp; Pint",
        "assets": {"hero": "el-segundo-dugout.webp", "food": "margherita.webp"},
        "alts": {"hero": "The Dugout: wooden picnic tables, a surfboard and TVs on a reclaimed-wood wall, and a Dodgers mural"},
        "dims": {"hero": [1600, 1067], "food": [500, 500]},
        "capacityText": "",  # not confirmed for the Dugout
    },
]

tpl = open("src/template.html").read()
for L in LOCATIONS:
    r = L["root"]
    assets = {"wordmark": "slice-pint-logo.webp", "badge": "slice-pint-logo.webp", **L["assets"]}
    cfg = {
        "location": L["loc"], **COMMON,
        "assets": {k: r + "assets/" + v for k, v in assets.items()},
        "alts": L["alts"], "captions": {},
        "dims": {"wordmark": [800, 367], "badge": [800, 367], **L["dims"]},
        "capacityText": L["capacityText"],
    }
    html = (tpl.replace("{{CONFIG}}", "/* Generated by build.py. Edit there, not here. */\nconst CONFIG = " + json.dumps(cfg, indent=2) + ";")
               .replace("{{ROOT}}", r).replace("{{LOC}}", L["loc"]).replace("{{FORM_NAME}}", L["form"])
               .replace("{{ADDRESS}}", L["address"]).replace("{{SPACE_COPY}}", L["space"])
               .replace("{{FOOD_ALT}}", L["food_alt"])
               .replace("{{GALLERY_HIDDEN}}", "" if L["gallery"] else " hidden"))
    assert "{{" not in html, L["out"]
    os.makedirs(os.path.dirname(L["out"]) or ".", exist_ok=True)
    open(L["out"], "w").write(html)
    print("built", L["out"])
